import argparse
import json
import sys
from pathlib import Path

from .completions import Completion, Literals, Paths, Resolution, Resource, resolve
from .help_model import Argument, Command, inspect_amp


def emit_mapping(lines: list[str], indent: int, name: str, values: list[tuple[str, str]]) -> None:
    if not values:
        return
    lines.append(f"{' ' * indent}{name}:")
    for key, value in values:
        description = value.replace("`", "'")
        lines.append(f"{' ' * (indent + 2)}{json.dumps(key)}: {json.dumps(description)}")


def dynamic_completion(resource: str) -> str:
    helper = '"${XDG_CONFIG_HOME:-$HOME/.config}/carapace/bin/amp-completions"'
    return f"$sh({helper} {resource})"


def completion_values(completion: Completion | None) -> list[str]:
    match completion:
        case Literals(values, delimiter):
            return [*values, *([f"$uniquelist({delimiter})"] if delimiter else [])]
        case Resource(name):
            return [dynamic_completion(name)]
        case Paths(macro):
            return [macro]
        case _:
            return []


def positional_values(
    positionals: list[tuple[Argument, Completion | None]],
) -> tuple[list[list[str]], list[str]]:
    fixed = [
        completion_values(completion)
        for argument, completion in positionals
        if not argument.variadic
    ]
    variadic = [
        completion_values(completion)
        for argument, completion in positionals
        if argument.variadic
    ]
    while fixed and not fixed[-1]:
        fixed.pop()
    return fixed, variadic[0] if variadic else []


def emit_command(
    command: Command,
    resolution: Resolution,
    indent: int,
    sequence: bool = False,
    parents: tuple[str, ...] = (),
) -> list[str]:
    prefix = " " * indent
    first = "- " if sequence else ""
    lines = [f"{prefix}{first}name: {json.dumps(command.name)}"]
    property_indent = indent + (2 if sequence else 0)
    property_prefix = " " * property_indent
    path = (*parents, command.name)

    if command.aliases:
        lines.append(f"{property_prefix}aliases: {json.dumps(command.aliases)}")
    if command.description:
        lines.append(f"{property_prefix}description: {json.dumps(command.description)}")

    option_key = "persistentflags" if command.name == "amp" else "flags"
    emit_mapping(
        lines,
        property_indent,
        option_key,
        [(option.spec_key, option.description) for option in command.options],
    )

    flags = resolution.flags(path, command)
    positional, positional_any = positional_values(resolution.positionals(path, command))
    if flags or positional or positional_any:
        lines.append(f"{property_prefix}completion:")
        if flags:
            lines.append(f"{property_prefix}  flag:")
            for name, completion in flags:
                values = completion_values(completion)
                lines.append(f"{property_prefix}    {json.dumps(name)}: {json.dumps(values)}")
        if positional:
            lines.append(f"{property_prefix}  positional:")
            for values in positional:
                lines.append(f"{property_prefix}    - {json.dumps(values)}")
        if positional_any:
            lines.append(f"{property_prefix}  positionalany: {json.dumps(positional_any)}")

    if command.commands:
        lines.append(f"{property_prefix}commands:")
        for child in command.commands:
            lines.extend(
                emit_command(
                    child,
                    resolution,
                    property_indent + 2,
                    sequence=True,
                    parents=path,
                )
            )

    return lines


def render(root: Command, version: str, resolution: Resolution | None = None) -> str:
    resolution = resolution or resolve(root)
    header = [
        "# Generated by generate.py. Do not edit by hand.",
        f"# Amp version: {version}",
        "# yaml-language-server: $schema=https://carapace.sh/schemas/command.json",
    ]
    return "\n".join([*header, *emit_command(root, resolution, 0), ""])


def manifest_completion(completion: Completion) -> dict[str, object]:
    if isinstance(completion, Literals):
        entry: dict[str, object] = {
            "literals": [value.split("\t", 1)[0] for value in completion.values]
        }
        if completion.delimiter is not None:
            entry["delimiter"] = completion.delimiter
        return entry
    if isinstance(completion, Resource):
        return {"resource": completion.name}
    if isinstance(completion, Paths):
        return {"paths": completion.macro}
    return {"exempt": completion.reason}


def build_manifest(root: Command, version: str, resolution: Resolution) -> dict[str, object]:
    argument_signatures = {}
    command_paths = []
    command_aliases = {}
    flag_paths = []
    persistent_flag_paths = []

    def visit(command: Command, parents: tuple[str, ...]) -> None:
        path = (*parents, command.name)
        command_path = " ".join(path)
        command_paths.append(command_path)
        if command.aliases:
            command_aliases[command_path] = sorted(command.aliases)
        if command.arguments:
            argument_signatures[command_path] = " ".join(
                argument.signature for argument in command.arguments
            )
        for option in command.options:
            flag_path = f"{command_path} {option.canonical}"
            flag_paths.append(flag_path)
            if command is root:
                persistent_flag_paths.append(flag_path)
        for child in command.commands:
            visit(child, path)

    visit(root, ())
    return {
        "amp_version": version,
        "argument_signatures": argument_signatures,
        "command_aliases": command_aliases,
        "command_paths": sorted(command_paths),
        "completion_diagnostics": sorted(resolution.diagnostics),
        "field_completions": {
            " ".join(key): manifest_completion(completion)
            for key, completion in resolution.completions.items()
        },
        "flag_paths": sorted(flag_paths),
        "manifest_version": 2,
        "persistent_flag_paths": sorted(persistent_flag_paths),
    }


def render_manifest(root: Command, version: str, resolution: Resolution) -> str:
    manifest = build_manifest(root, version, resolution)
    return json.dumps(manifest, indent=2, sort_keys=True) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate a Carapace spec from Amp's help output")
    parser.add_argument("--amp", default="amp", help="path to the Amp executable")
    parser.add_argument("--output", type=Path, default=Path("amp.yaml"))
    parser.add_argument(
        "--manifest-output",
        type=Path,
        default=Path("amp-manifest.json"),
    )
    arguments = parser.parse_args()

    root, version = inspect_amp(arguments.amp)
    resolution = resolve(root)
    for diagnostic in resolution.diagnostics:
        print(f"warning: {diagnostic}", file=sys.stderr)
    arguments.output.write_text(render(root, version, resolution))
    arguments.manifest_output.write_text(render_manifest(root, version, resolution))


if __name__ == "__main__":
    main()
